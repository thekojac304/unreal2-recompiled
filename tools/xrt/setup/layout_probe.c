/* layout_probe.c - the structure layouts the translated code shares with the runtime, as seen by one compiler.
 * Built with the runtime's compiler (MSVC, normal headers) it prints C11 static assertions; the generator then
 * compiles those assertions with the bundled clang-cl and the minimal headers (include/), so a layout difference
 * between the two halves stops the build instead of corrupting memory at run time. */
#include <stddef.h>
#include <stdio.h>
#include "xrt.h"

#define S(t) printf("_Static_assert(sizeof(" #t ") == %zu, \"sizeof " #t "\");\n", sizeof(t))
#define A(t) printf("_Static_assert(_Alignof(" #t ") == %zu, \"alignof " #t "\");\n", _Alignof(t))
#define O(t, f) printf("_Static_assert(offsetof(" #t ", " #f ") == %zu, \"" #t "." #f "\");\n", offsetof(t, f))

int main(void) {
    printf("/* generated by layout_probe.c (runtime compiler) */\n#include <stddef.h>\n#include \"xrt.h\"\n");
    S(CPU); A(CPU);
    O(CPU, r); O(CPU, cf); O(CPU, df); O(CPU, eflags_rest); O(CPU, fs_base); O(CPU, rv); O(CPU, pc); O(CPU, st);
    O(CPU, top); O(CPU, fcw); O(CPU, fsw); O(CPU, hist); O(CPU, hpos); O(CPU, world_floor); O(CPU, thread);
    S(XrtCallCache); O(XrtCallCache, va); O(XrtCallCache, gen); O(XrtCallCache, fn); O(XrtCallCache, flags);
    S(XrtEhPad); A(XrtEhPad);
    S(XrtThreadEh); O(XrtThreadEh, host_calls); O(XrtThreadEh, eh_pads);
    S(XrtLiftedModule); S(XrtMark); S(XrtWatchDef);
    S(void*); S(long); S(long double); S(wchar_t); S(size_t);
    return 0;
}
