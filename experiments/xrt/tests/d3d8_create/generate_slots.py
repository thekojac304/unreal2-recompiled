"""Generate named traps from the preserved, characterized 97-slot declaration."""
import sys
from pathlib import Path
HERE=Path(__file__).resolve().parent
sys.path.insert(0,str(HERE.parent/'d3d8_device'))
from slots import SLOTS
supported={'QueryInterface','AddRef','Release','GetDirect3D','GetCreationParameters','Clear','Present','SetRenderState'}
lines=['/* Generated by tests/d3d8_create/generate_slots.py; only measured methods omitted from traps. */']
for slot,(name,args) in enumerate(SLOTS):
    if name not in supported:
        lines.append(f'static void d8_device_{name}(CPU*c) {{ d8_device_object(c,ARG(0));xrt_fatal(c,76,"IDirect3DDevice8 unsupported slot {slot} {name}"); }}')
lines.append('static const char*const d8_device_slot_names[97]={'+','.join('"D8Device.'+n+'"'for n,_ in SLOTS)+'};')
lines.append('#define XRT_D3D8_DEVICE_BINDINGS \\\n'+' \\\n'.join('{"xrt.com","D8Device.'+n+'",d8_device_'+n+'},'for n,_ in SLOTS))
(HERE.parents[1]/'runtime/d3d8_device_slots.inc').write_text('\n'.join(lines)+'\n')
